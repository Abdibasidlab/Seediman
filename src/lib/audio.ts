// Narration (Gemini recordings with word highlighting), Quran recitation, and UI sound effects.
// Every narrated line is a Gemini recording (npm run narration). There is deliberately no device-voice fallback.

import { narrationKey } from './narrationKey';

type Lang = 'en' | 'ar';

let soundOn = true;
const listeners = new Set<(on: boolean) => void>();
export const isSoundOn = () => soundOn;
export function setSoundOn(on: boolean) {
  soundOn = on;
  if (!on) stopAll();
  listeners.forEach(l => l(on));
}
export const onSoundChange = (fn: (on: boolean) => void) => { listeners.add(fn); return () => { listeners.delete(fn); }; };

// ---------- cancellation ----------
let gen = 0;
let currentAudio: HTMLAudioElement | null = null;
const timers = new Set<number>();
const pending = new Set<() => void>();
export function stopAll() {
  gen++;
  if (currentAudio) { currentAudio.pause(); currentAudio = null; }
  timers.forEach(t => clearTimeout(t)); timers.clear();
  pending.forEach(r => r()); pending.clear();
}
const wait = (ms: number) => new Promise<void>(res => {
  const done = () => { pending.delete(done); res(); };
  pending.add(done);
  const t = window.setTimeout(() => { timers.delete(t); done(); }, ms); timers.add(t);
});

// ---------- recorded narration (Gemini TTS, generated by scripts/gen-narration.ts) ----------
const manifestReady: Promise<Record<string, { file: string; duration: number }> | null> =
  fetch('audio/narration/manifest.json').then(r => (r.ok ? r.json() : null)).catch(() => null);

/**
 * Clips are fetched whole and played from memory. Pointing <audio> straight at the file lets Chrome make
 * range requests through its media cache, which sometimes fails (ERR_CACHE_OPERATION_NOT_SUPPORTED).
 */
const clips = new Map<string, Promise<string | null>>();
function loadClip(url: string): Promise<string | null> {
  let p = clips.get(url);
  if (!p) {
    const get = (init?: RequestInit) => fetch(url, init).then(r => (r.ok ? r.blob() : null)).catch(() => null);
    // a corrupted Chrome cache entry fails the first fetch; the retry skips the cache entirely
    p = get().then(b => b ?? get({ cache: 'no-store' })).then(b => (b ? URL.createObjectURL(b) : null));
    p.then(u => { if (!u) clips.delete(url); }); // let a failed load be retried
    clips.set(url, p);
  }
  return p;
}

type PlayResult = 'ok' | 'failed' | 'cancelled';

/** Play a recorded line, lighting each word in proportion to its length across the clip. */
async function playRecorded(url: string, duration: number, weights: number[], my: number, onWord?: (i: number) => void): Promise<PlayResult> {
  const src = await loadClip(url);
  if (gen !== my) return 'cancelled';
  if (!src) return 'failed';
  return new Promise(resolve => {
    const a = new Audio(src); currentAudio = a;
    const total = weights.reduce((x, y) => x + y, 0);
    const lead = 0.12; // TTS clips start with a little silence
    let acc = 0;
    const starts = weights.map(w => { const s = acc; acc += w; return s / total; });
    let idx = -1;
    const tick = () => {
      if (gen !== my || a.paused) return;
      const d = (isFinite(a.duration) ? a.duration : duration) - lead;
      const f = Math.max(0, (a.currentTime - lead) / d);
      let k = 0; for (let i = 0; i < starts.length; i++) if (starts[i] <= f) k = i;
      if (k !== idx) { idx = k; onWord?.(k); }
      requestAnimationFrame(tick);
    };
    a.onplay = () => requestAnimationFrame(tick);
    a.onended = () => resolve(gen === my ? 'ok' : 'cancelled');
    a.onpause = () => { if (gen !== my) resolve('cancelled'); };
    a.onerror = () => resolve('failed');
    a.play().catch(() => resolve(gen === my ? 'failed' : 'cancelled'));
  });
}

// ---------- narration ----------
const SAL_AR = 'صَلَّى اللهُ عَلَيْهِ وَسَلَّمَ';
const SAL_EN = 'sallallahu alayhi wa sallam';
const spokenToken = (tok: string, lang: Lang) => tok.replace('ﷺ', lang === 'ar' ? SAL_AR : SAL_EN);

export const tokens = (text: string) => text.split(/\s+/).filter(Boolean);

export interface NarrateOpts { lang: Lang; onWord?: (i: number) => void; rate?: number }

/** Speak `text`, calling onWord(i) as each displayed token is reached. Resolves when done or cancelled. */
export async function narrate(text: string, { lang, onWord, rate }: NarrateOpts): Promise<boolean> {
  stopAll();
  const my = gen;
  const toks = tokens(text);
  const r = rate ?? (lang === 'ar' ? 0.78 : 0.92);
  const est = (t: string) => (lang === 'ar' ? 150 + t.length * 85 : 110 + t.length * 58) / r;

  const timed = async () => {
    for (let i = 0; i < toks.length; i++) { if (gen !== my) return false; onWord?.(i); await wait(est(spokenToken(toks[i], lang))); }
    await wait(250);
    return gen === my;
  };

  if (!soundOn) return timed();
  const rec = (await manifestReady)?.[narrationKey(lang, text)];
  if (gen !== my) return false;
  if (rec) {
    const r = await playRecorded(`audio/narration/${rec.file}`, rec.duration, toks.map(t => spokenToken(t, lang).length + 3), my, onWord);
    if (r !== 'failed') return r === 'ok';
    // the recording couldn't play: light the words at reading pace rather than switch to a robotic device voice
    return timed();
  }

  // No Gemini recording for this line: light the words at reading pace in silence.
  // The device's built-in voice is never used — it sounds robotic next to the recorded narration.
  console.warn('[narration] no recording for:', lang, text, '— run npm run narration');
  return timed();
}

/** Say a sentence once in Arabic then once in English (used for answers). */
export async function narratePair(ar: string, en: string, onAr?: (i: number) => void, onEn?: (i: number) => void) {
  if (!(await narrate(ar, { lang: 'ar', onWord: onAr }))) return false;
  onAr?.(-1);
  await wait(250);
  return narrate(en, { lang: 'en', onWord: onEn });
}

// ---------- Quran recitation ----------
/**
 * Play a phrase from a full-ayah recording: onWord(i) fires as each word starts (times in `starts`),
 * and playback fades out at `end` (the reciter's pause after the phrase).
 */
/** `starts[i]` is when word i is recited; `again` lists repeats (a word said a second time lights up again) */
export async function playClip(url: string, starts: number[], end: number, onWord: (i: number) => void, fadeLen = 0.28, again: { t: number; i: number }[] = []): Promise<boolean> {
  const events = [...starts.map((t, i) => ({ t, i })), ...again].sort((a, b) => a.t - b.t);
  stopAll();
  const my = gen;
  const src = await loadClip(url);
  if (gen !== my) return false;
  return new Promise(resolve => {
    const a = new Audio(src ?? url); currentAudio = a;
    let idx = -1, fading = false, settled = false;
    const finish = (ok: boolean) => { if (settled) return; settled = true; if (gen === my) onWord(-1); resolve(ok && gen === my); };
    const tick = () => {
      if (settled || gen !== my) return;
      const ct = a.currentTime;
      let k = -1; for (const e of events) if (e.t <= ct + 0.04) k = e.i;
      if (k !== idx && k >= 0) { idx = k; onWord(k); }
      if (ct >= end - fadeLen && !fading) {
        fading = true; const v0 = a.volume, t0 = performance.now();
        const fade = () => {
          const f = Math.min(1, (performance.now() - t0) / (fadeLen * 1000));
          a.volume = v0 * (1 - f);
          if (f < 1 && gen === my) requestAnimationFrame(fade); else { a.pause(); finish(true); }
        };
        requestAnimationFrame(fade);
      }
      if (!a.paused) requestAnimationFrame(tick);
    };
    a.onplay = () => requestAnimationFrame(tick);
    a.onended = () => finish(true);
    a.onpause = () => { if (gen !== my) finish(false); };
    a.onerror = () => finish(false);
    a.play().catch(() => finish(false));
  });
}

// ---------- sound effects ----------
let ctx: AudioContext | null = null;
const ac = () => (ctx ??= new AudioContext());
function tone(freq: number, start: number, dur: number, type: OscillatorType, gain: number) {
  const c = ac(), o = c.createOscillator(), g = c.createGain();
  o.type = type; o.frequency.value = freq;
  g.gain.setValueAtTime(0.0001, c.currentTime + start);
  g.gain.exponentialRampToValueAtTime(gain, c.currentTime + start + 0.015);
  g.gain.exponentialRampToValueAtTime(0.0001, c.currentTime + start + dur);
  o.connect(g).connect(c.destination);
  o.start(c.currentTime + start); o.stop(c.currentTime + start + dur + 0.05);
}
export const sfx = {
  correct() { if (!soundOn) return; tone(1046.5, 0, 0.5, 'sine', 0.12); tone(1318.5, 0.08, 0.6, 'sine', 0.09); },
  retry() { if (!soundOn) return; tone(261.6, 0, 0.22, 'triangle', 0.07); },
  pulse() { if (!soundOn) return; tone(784, 0, 1.2, 'sine', 0.06); tone(1568, 0, 0.8, 'sine', 0.02); },
  complete() { if (!soundOn) return; [523.3, 659.3, 784, 1046.5].forEach((f, i) => tone(f, i * 0.14, 1.4, 'sine', 0.07)); },
};

/** Soft light burst at a screen position (used for correct answers). */
export function burstAt(x: number, y: number) {
  const el = document.createElement('div');
  el.className = 'burst'; el.style.left = x + 'px'; el.style.top = y + 'px';
  document.body.appendChild(el);
  setTimeout(() => el.remove(), 750);
}
export function burstOn(el: Element | null) {
  if (!el) return;
  const r = el.getBoundingClientRect(); burstAt(r.left + r.width / 2, r.top + r.height / 2);
}
